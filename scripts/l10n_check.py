#!/usr/bin/env python3
"""Catalog check: every T("…")/L10n.f("…") key must have EN and ES in Localization/catalog.tsv; regenerates the Swift catalog.
Usage: l10n_check.py [--write-missing]  (prints coverage; exit 1 when keys are missing)."""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
keys = set()
for f in (root / "Sources").rglob("*.swift"):
    for m in re.finditer(r'(?:\bT|L10n\.t|L10n\.f)\(\s*"((?:[^"\\]|\\.)*)"', f.read_text()): keys.add(m.group(1))
tsv = root / "Localization" / "catalog.tsv"
cat = {}
if tsv.exists():
    for line in tsv.read_text().splitlines():
        if not line.strip() or line.startswith("#"): continue
        ro, en, es = (line.split("\t") + ["", ""])[:3]; cat[ro] = (en, es)
missing = sorted(k for k in keys if not cat.get(k, ("", ""))[0] or not cat.get(k, ("", ""))[1])
if "--write-missing" in sys.argv:
    with tsv.open("a") as o:
        for k in missing:
            if k not in cat: o.write(f"{k}\t\t\n")
def esc(x): return x.replace("\\", "\\\\").replace('"', '\\"') if False else x
out = ["// GENERATED by scripts/l10n_check.py from Localization/catalog.tsv — do not edit by hand.", "enum L10nCatalog {", "    static let entries: [String: (String, String)] = ["]
for ro, (en, es) in sorted(cat.items()):
    if ro in keys and en and es: out.append(f'        "{ro}": ("{en}", "{es}"),')
out += (["    ]"] if len(out) > 3 else ["        :]"]) + ["}"]
(root / "Sources/SadrogCore/L10nCatalog.swift").write_text("\n".join(out) + "\n")
print(f"chei: {len(keys)}, traduse complet: {len(keys) - len(missing)}, lipsă: {len(missing)}")
for k in missing[:400]: print("LIPSĂ:", k)
sys.exit(1 if missing else 0)
